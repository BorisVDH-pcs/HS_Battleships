/**
 * Writes `src/lib/icons.js` from whatever is in `public/icons`.
 *
 * The icon picker needs the list of available artwork, and the browser cannot
 * read a directory. Vite's `import.meta.glob` cannot help either: `public/` is
 * copied verbatim and never passes through the module graph, which is exactly
 * why the icons are addressable as plain URLs in the first place.
 *
 * So the list is generated and committed. It is a build input, not a build
 * output — a stale manifest shows an icon that 404s, or hides one that exists,
 * and neither breaks the game. Re-run it after adding artwork:
 *
 *     npm run icons:manifest
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const iconDir = join(here, '..', 'public', 'icons');
const out = join(here, '..', 'src', 'lib', 'icons.js');

const slugs = readdirSync(iconDir)
  .filter((f) => f.toLowerCase().endsWith('.png'))
  .map((f) => f.slice(0, -4))
  .sort((a, b) => a.localeCompare(b));

const body = `// Generated by scripts/build-icon-manifest.mjs — do not edit by hand.
// Re-run \`npm run icons:manifest\` after adding artwork to public/icons.
//
// Every slug is a file in public/icons, without the .png. TileIcon builds the
// URL from BASE_URL, so nothing here is a path.

export const ICONS = [
${slugs.map((s) => `  '${s}',`).join('\n')}
];

/** Icons whose slug contains every word of \`query\`, in any order. */
export function searchIcons(query) {
  const words = query.toLowerCase().split(' ').filter(Boolean);
  if (words.length === 0) return ICONS;
  return ICONS.filter((slug) => {
    const haystack = slug.replace(/_/g, ' ');
    return words.every((word) => haystack.includes(word));
  });
}

/** 'dragon_warhammer' -> 'Dragon warhammer', for a picker label. */
export function iconLabel(slug) {
  const words = slug.replace(/_/g, ' ');
  return words.charAt(0).toUpperCase() + words.slice(1);
}
`;

writeFileSync(out, body, 'utf8');
console.log(`icons.js: ${slugs.length} icons`);
